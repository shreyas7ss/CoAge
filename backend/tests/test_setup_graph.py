"""Setup graph tests using a FakeLLM and InMemorySaver."""

from langgraph.checkpoint.memory import InMemorySaver
from langgraph.types import Command

from app.agents.setup.graph import build_setup_graph
from app.schemas.llm import DraftedCriterion, DraftedPackage, DraftedQuestion
from tests.fake_llm import FakeLLM

TOPICS = [{"id": "t1", "name": "Hashing"}, {"id": "t2", "name": "Complexity"}]
QUESTIONS = [
    {"q_id": "q1", "prompt": "Define a hash collision.", "qtype": "short_answer", "max_marks": 10.0}
]


def _drafted_package(marks=(6.0, 4.0), topic="t1"):
    return DraftedPackage(
        questions=[
            DraftedQuestion(
                q_id="q1",
                reference_answer="A collision occurs when two keys map to the same index.",
                common_misconceptions=["Thinks collisions mean data is lost"],
                rubric=[
                    DraftedCriterion(criterion="Defines a collision", marks=marks[0], topic=topic),
                    DraftedCriterion(criterion="Explains chaining", marks=marks[1], topic="t1"),
                ],
            )
        ]
    )


def _run_initial(llm, **overrides):
    saver = InMemorySaver()
    graph = build_setup_graph(checkpointer=saver, llm_factory=lambda: llm)
    config = {"configurable": {"thread_id": "setup-1"}}
    initial = {
        "assignment_id": "a1",
        "course_topics": TOPICS,
        "questions": QUESTIONS,
        "package_draft": None,
        "skip_draft": False,
        "rejection_count": 0,
        "validation_errors": [],
    }
    initial.update(overrides)
    result = graph.invoke(initial, config)
    return graph, config, result


def _interrupt_value(result):
    interrupts = result["__interrupt__"]
    assert interrupts, "expected an interrupt"
    return getattr(interrupts[0], "value", interrupts[0])


def test_draft_interrupts_at_faculty_review() -> None:
    llm = FakeLLM({DraftedPackage: _drafted_package})
    _, _, result = _run_initial(llm)
    payload = _interrupt_value(result)
    assert payload["package"] is not None
    assert payload["assignment_id"] == "a1"


def test_approve_finalizes_package() -> None:
    llm = FakeLLM({DraftedPackage: _drafted_package})
    graph, config, result = _run_initial(llm)
    payload = _interrupt_value(result)

    final = graph.invoke(
        Command(resume={"approved": True, "package": payload["package"]}), config
    )
    assert final["status"] == "approved"
    assert final["final_package"]["questions"][0]["q_id"] == "q1"


def test_reject_loops_back_and_redrafts() -> None:
    llm = FakeLLM({DraftedPackage: _drafted_package})
    graph, config, result = _run_initial(llm)

    # Reject with comments (no package edit) -> redraft -> interrupt again.
    second = graph.invoke(
        Command(resume={"approved": False, "comments": "Add a third criterion"}), config
    )
    assert second["__interrupt__"], "expected a second interrupt after redraft"
    # The second draft must have been regenerated by the LLM.
    payload2 = _interrupt_value(second)
    assert payload2["package"] is not None


def test_reject_twice_exhausts_and_ends_in_draft() -> None:
    llm = FakeLLM({DraftedPackage: _drafted_package})
    graph, config, result = _run_initial(llm)

    graph.invoke(Command(resume={"approved": False, "comments": "again"}), config)
    graph.invoke(Command(resume={"approved": False, "comments": "again 2"}), config)
    final = graph.invoke(Command(resume={"approved": False, "comments": "again 3"}), config)
    assert final["status"] == "draft"
    assert final["final_package"] is not None


def test_validation_repairs_marks_to_sum() -> None:
    # LLM returns 6 + 3 = 9 for a 10-mark question; validator must rescale to 10.
    llm = FakeLLM({DraftedPackage: lambda: _drafted_package(marks=(6.0, 3.0))})
    _, _, result = _run_initial(llm)
    payload = _interrupt_value(result)
    marks = [c["marks"] for c in payload["package"]["questions"][0]["rubric"]]
    assert round(sum(marks), 2) == 10.0


def test_invalid_topic_is_flagged() -> None:
    llm = FakeLLM({DraftedPackage: lambda: _drafted_package(topic="bogus-topic")})
    _, _, result = _run_initial(llm)
    payload = _interrupt_value(result)
    assert any("invalid topic" in e for e in payload["validation_errors"])
